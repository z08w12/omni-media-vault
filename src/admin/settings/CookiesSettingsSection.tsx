import { useEffect, useRef, useState, useTransition } from "react";
import {
  AlertCircle,
  Check,
  CheckCircle2,
  Copy,
  Cookie,
  FileEdit,
  History,
  Info,
  Loader2,
  RefreshCw,
  RotateCcw,
  Trash2,
  Upload,
} from "lucide-react";
import * as api from "../api";
import { Modal } from "../Modal";
import { useToast } from "@/components/ToastContext";
import { SettingsSection } from "./SettingsSection";
import "@/styles/cookies-settings.css";

type Props = {
  active: boolean;
};

function formatBytes(bytes: number): string {
  if (bytes <= 0) return "0 B";
  const units = ["B", "KB", "MB", "GB"];
  const i = Math.floor(Math.log(bytes) / Math.log(1024));
  return `${(bytes / Math.pow(1024, i)).toFixed(i > 0 ? 1 : 0)} ${units[i]}`;
}

function formatDate(dateStr?: string): string {
  if (!dateStr) return "-";
  try {
    const d = new Date(dateStr);
    if (isNaN(d.getTime())) return dateStr;
    return d.toLocaleString("zh-CN", {
      year: "numeric",
      month: "2-digit",
      day: "2-digit",
      hour: "2-digit",
      minute: "2-digit",
      second: "2-digit",
      hour12: false,
    });
  } catch {
    return dateStr;
  }
}

export function CookiesSettingsSection({ active }: Props) {
  const { show } = useToast();
  const [, startTransition] = useTransition();

  const [loading, setLoading] = useState(false);
  const [items, setItems] = useState<api.PlatformCookieStatus[]>([]);
  const [error, setError] = useState<string>("");

  // Editing state
  const [editingPlatform, setEditingPlatform] = useState<api.PlatformCookieStatus | null>(null);
  const [editorContent, setEditorContent] = useState("");
  const [editorLoading, setEditorLoading] = useState(false);
  const [savingContent, setSavingContent] = useState(false);

  // Restore confirmation modal
  const [restoreTarget, setRestoreTarget] = useState<api.PlatformCookieStatus | null>(null);
  const [restoring, setRestoring] = useState(false);

  // Delete confirmation modal
  const [deleteTarget, setDeleteTarget] = useState<api.PlatformCookieStatus | null>(null);
  const [deleting, setDeleting] = useState(false);

  // Upload input ref
  const fileInputRef = useRef<HTMLInputElement>(null);
  const uploadTargetRef = useRef<api.PlatformCookieStatus | null>(null);

  // Hash copied state
  const [copiedSha, setCopiedSha] = useState<string | null>(null);

  async function loadCookies(silent = false) {
    if (!silent) setLoading(true);
    setError("");
    try {
      const data = await api.listCookies();
      startTransition(() => {
        setItems(data);
      });
    } catch (err) {
      const msg = err instanceof Error ? err.message : "获取 Cookie 状态失败";
      setError(msg);
      show(msg, "error");
    } finally {
      if (!silent) setLoading(false);
    }
  }

  useEffect(() => {
    if (active) {
      void loadCookies();
    }
  }, [active]);

  // Open editor
  async function handleOpenEdit(item: api.PlatformCookieStatus) {
    setEditingPlatform(item);
    setEditorLoading(true);
    setEditorContent("");
    try {
      const hasData = Boolean(item.configured ?? item.exists);
      if (hasData) {
        const res = await api.getCookieContent(item.platform);
        setEditorContent(res.content);
      } else {
        setEditorContent(
          `# Netscape HTTP Cookie File\n# https://curl.se/docs/http-cookies.html\n# This file was generated by Omni Media Vault\n# domain\tinclude_subdomains\tpath\tsecure\texpiry\tname\tvalue\n`
        );
      }
    } catch (err) {
      const msg = err instanceof Error ? err.message : "获取 Cookie 内容失败";
      show(msg, "error");
    } finally {
      setEditorLoading(false);
    }
  }

  // Save edited content
  async function handleSaveEdit() {
    if (!editingPlatform) return;
    setSavingContent(true);
    try {
      await api.saveCookieContent(editingPlatform.platform, editorContent);
      show(`${editingPlatform.displayName} Cookie 保存成功`, "success");
      setEditingPlatform(null);
      void loadCookies(true);
    } catch (err) {
      const msg = err instanceof Error ? err.message : "保存 Cookie 失败";
      show(msg, "error");
    } finally {
      setSavingContent(false);
    }
  }

  // Trigger file upload
  function handleTriggerUpload(item: api.PlatformCookieStatus) {
    uploadTargetRef.current = item;
    if (fileInputRef.current) {
      fileInputRef.current.value = "";
      fileInputRef.current.click();
    }
  }

  // Handle uploaded file
  async function handleFileSelected(e: React.ChangeEvent<HTMLInputElement>) {
    const file = e.target.files?.[0];
    const target = uploadTargetRef.current;
    if (!file || !target) return;

    if (file.size > 10 * 1024 * 1024) {
      show("文件大小不能超过 10MB", "error");
      return;
    }

    try {
      await api.uploadCookieFile(target.platform, file);
      show(`${target.displayName} Cookie 文件上传成功`, "success");
      void loadCookies(true);
    } catch (err) {
      const msg = err instanceof Error ? err.message : "上传 Cookie 文件失败";
      show(msg, "error");
    }
  }

  // Confirm Restore
  async function handleConfirmRestore() {
    if (!restoreTarget) return;
    setRestoring(true);
    try {
      await api.restoreCookie(restoreTarget.platform);
      show(`${restoreTarget.displayName} Cookie 已成功恢复至上个备份版本`, "success");
      setRestoreTarget(null);
      void loadCookies(true);
    } catch (err) {
      const msg = err instanceof Error ? err.message : "恢复备份失败";
      show(msg, "error");
    } finally {
      setRestoring(false);
    }
  }

  // Confirm Delete
  async function handleConfirmDelete() {
    if (!deleteTarget) return;
    setDeleting(true);
    try {
      await api.deleteCookie(deleteTarget.platform);
      show(`${deleteTarget.displayName} Cookie 已移除`, "success");
      setDeleteTarget(null);
      void loadCookies(true);
    } catch (err) {
      const msg = err instanceof Error ? err.message : "删除失败";
      show(msg, "error");
    } finally {
      setDeleting(false);
    }
  }

  // Copy SHA256
  function handleCopySha(sha: string) {
    void navigator.clipboard.writeText(sha).then(() => {
      setCopiedSha(sha);
      show("SHA-256 哈希已复制", "info");
      setTimeout(() => setCopiedSha(null), 2000);
    });
  }

  // Format pre-check for textarea
  const lineCount = editorContent
    ? editorContent.split("\n").filter((l) => l.trim().length > 0 && !l.startsWith("#")).length
    : 0;
  const isSuspiciousHtml = editorContent.trim().toLowerCase().startsWith("<!doctype") ||
    editorContent.trim().toLowerCase().startsWith("<html");
  const isSuspiciousJson = editorContent.trim().startsWith("{");

  if (!active) return null;

  return (
    <div className="admin-cookies-settings">
      {/* Hidden file input */}
      <input
        ref={fileInputRef}
        type="file"
        accept=".txt,text/plain"
        style={{ display: "none" }}
        onChange={(e) => void handleFileSelected(e)}
      />

      <SettingsSection
        id="config-cookies"
        index="05"
        icon={<Cookie size={16} />}
        title="平台 Cookie"
        description="管理各大平台视频解析与下载所需的登录认证凭据 (Netscape 格式 cookies.txt)"
      >
        {/* Information banner */}
        <div className="cookies-info-banner">
          <Info size={18} className="cookies-info-banner__icon" aria-hidden="true" />
          <div>
            <strong>格式与安全提示：</strong>
            <span>
              支持标准 Netscape HTTP Cookie 格式（制表符分隔），可使用浏览器扩展（如 Chrome「Get cookies.txt LOCALLY」）导出后在此处上传或直接粘贴。
              所有更新保存前系统会自动生成安全备份（.bak），支持一键无缝回滚；系统升级与版本部署时 Cookie 文件永久受保护，绝不丢失。
            </span>
          </div>
        </div>

        {/* Toolbar */}
        <div style={{ display: "flex", justifyContent: "flex-end", marginBottom: 8 }}>
          <button
            type="button"
            className="admin-btn"
            onClick={() => void loadCookies()}
            disabled={loading}
            title="刷新 Cookie 状态"
          >
            <RefreshCw size={14} className={loading ? "admin-spin" : ""} aria-hidden="true" />
            <span>刷新状态</span>
          </button>
        </div>

        {error && (
          <div className="cookies-info-banner" style={{ borderColor: "var(--danger)" }}>
            <AlertCircle size={18} style={{ color: "var(--danger)" }} aria-hidden="true" />
            <span>{error}</span>
          </div>
        )}

        {/* Platform Cards */}
        <div className="cookies-grid">
          {items.map((item) => {
            const isConfigured = Boolean(item.configured ?? item.exists);
            const updatedTime = item.updatedAt || item.modTime;

            return (
              <div
                key={item.platform}
                className={`cookie-card ${isConfigured ? "is-configured" : "is-empty"}`}
              >
                <div>
                  <div className="cookie-card__header">
                    <div className="cookie-card__title-group">
                      <div className="cookie-card__platform-icon" aria-hidden="true">
                        <Cookie size={18} />
                      </div>
                      <div>
                        <div className="cookie-card__title">{item.displayName}</div>
                        <div className="cookie-card__filename">{item.fileName}</div>
                      </div>
                    </div>
                    <span className={`cookie-badge ${isConfigured ? "is-success" : "is-muted"}`}>
                      {isConfigured ? (
                        <>
                          <CheckCircle2 size={12} aria-hidden="true" />
                          <span>已配置</span>
                        </>
                      ) : (
                        <>
                          <AlertCircle size={12} aria-hidden="true" />
                          <span>未配置</span>
                        </>
                      )}
                    </span>
                  </div>

                  <div className="cookie-card__body">
                    <div className="cookie-stat-row">
                      <span className="cookie-stat-row__label">文件大小</span>
                      <span className="cookie-stat-row__value">{formatBytes(item.size)}</span>
                    </div>
                    <div className="cookie-stat-row">
                      <span className="cookie-stat-row__label">有效 Cookie</span>
                      <span className="cookie-stat-row__value">{item.lineCount} 条</span>
                    </div>
                    <div className="cookie-stat-row">
                      <span className="cookie-stat-row__label">修改时间</span>
                      <span className="cookie-stat-row__value">{formatDate(updatedTime)}</span>
                    </div>
                    {item.sha256 && (
                      <div className="cookie-stat-row">
                        <span className="cookie-stat-row__label">SHA-256</span>
                        <span
                          className="cookie-stat-row__value cookie-sha256-code"
                          title={`点击复制: ${item.sha256}`}
                          onClick={() => handleCopySha(item.sha256!)}
                        >
                          {item.sha256.substring(0, 10)}...
                          {copiedSha === item.sha256 ? (
                            <Check size={12} style={{ color: "#10b981" }} />
                          ) : (
                            <Copy size={12} />
                          )}
                        </span>
                      </div>
                    )}

                    {item.hasBackup && (
                      <div className="cookie-card__backup-notice">
                        <History size={12} aria-hidden="true" />
                        <span>已保留最近备份 (.bak)</span>
                      </div>
                    )}
                  </div>
                </div>

                {/* Actions */}
                <div className="cookie-card__actions">
                  <button
                    type="button"
                    className="admin-btn is-primary"
                    onClick={() => void handleOpenEdit(item)}
                    title="查看或在线修改 Cookie 内容"
                  >
                    <FileEdit size={13} aria-hidden="true" />
                    <span>编辑</span>
                  </button>
                  <button
                    type="button"
                    className="admin-btn"
                    onClick={() => handleTriggerUpload(item)}
                    title="选择本地 cookies.txt 文件直接上传"
                  >
                    <Upload size={13} aria-hidden="true" />
                    <span>上传</span>
                  </button>
                  {item.hasBackup && (
                    <button
                      type="button"
                      className="admin-btn is-icon-only"
                      onClick={() => setRestoreTarget(item)}
                      title="恢复到上一个备份版本"
                    >
                      <RotateCcw size={13} aria-hidden="true" />
                    </button>
                  )}
                  {isConfigured && (
                    <button
                      type="button"
                      className="admin-btn is-danger is-icon-only"
                      onClick={() => setDeleteTarget(item)}
                      title="清空此平台 Cookie"
                    >
                      <Trash2 size={13} aria-hidden="true" />
                    </button>
                  )}
                </div>
              </div>
            );
          })}
        </div>
      </SettingsSection>

      {/* View & Edit Modal */}
      {editingPlatform && (
        <Modal
          open={Boolean(editingPlatform)}
          title={`编辑 ${editingPlatform.displayName} Cookie (${editingPlatform.fileName})`}
          onClose={savingContent ? () => undefined : () => setEditingPlatform(null)}
          footer={
            <>
              <button
                type="button"
                className="admin-btn"
                onClick={() => setEditingPlatform(null)}
                disabled={savingContent}
              >
                取消
              </button>
              <button
                type="button"
                className="admin-btn is-primary"
                onClick={() => void handleSaveEdit()}
                disabled={savingContent || editorLoading || isSuspiciousHtml || isSuspiciousJson}
              >
                {savingContent ? (
                  <>
                    <Loader2 size={14} className="admin-spin" aria-hidden="true" />
                    <span>保存中...</span>
                  </>
                ) : (
                  <span>保存并应用</span>
                )}
              </button>
            </>
          }
        >
          <div className="cookie-editor-dialog">
            <div className="cookie-editor-dialog__tip">
              每行一条记录，使用制表符（Tab）分隔：
              <code style={{ fontSize: "11px", display: "block", marginTop: 4 }}>
                domain \t include_subdomains \t path \t secure \t expiry \t name \t value
              </code>
            </div>

            {(isSuspiciousHtml || isSuspiciousJson) && (
              <div
                className="cookies-info-banner"
                style={{ borderColor: "var(--danger)", color: "var(--danger)" }}
              >
                <AlertCircle size={16} aria-hidden="true" />
                <span>
                  检测到内容包含 HTML 网页或 JSON 响应，不是合法的 Netscape Cookie 文本，无法保存。
                </span>
              </div>
            )}

            {editorLoading ? (
              <div style={{ display: "flex", justifyContent: "center", padding: 40 }}>
                <Loader2 size={24} className="admin-spin" />
              </div>
            ) : (
              <textarea
                className="cookie-editor-dialog__textarea"
                value={editorContent}
                onChange={(e) => setEditorContent(e.target.value)}
                placeholder="# Netscape HTTP Cookie File&#10;domain&#9;TRUE&#9;/&#9;TRUE&#9;1893456000&#9;session_id&#9;xyz123"
                spellCheck={false}
              />
            )}

            <div className="cookie-editor-dialog__footer-stats">
              <span>有效记录: {lineCount} 条</span>
              <span>总字符: {editorContent.length} 字节</span>
            </div>
          </div>
        </Modal>
      )}

      {/* Restore Confirmation Modal */}
      {restoreTarget && (
        <Modal
          open={Boolean(restoreTarget)}
          title="确认恢复备份"
          onClose={restoring ? () => undefined : () => setRestoreTarget(null)}
          footer={
            <>
              <button
                type="button"
                className="admin-btn"
                onClick={() => setRestoreTarget(null)}
                disabled={restoring}
              >
                取消
              </button>
              <button
                type="button"
                className="admin-btn is-primary"
                onClick={() => void handleConfirmRestore()}
                disabled={restoring}
              >
                {restoring ? "正在恢复..." : "确认恢复"}
              </button>
            </>
          }
        >
          <p style={{ margin: "16px 0", fontSize: "14px", lineHeight: "1.6" }}>
            确定要将 <strong>{restoreTarget.displayName}</strong> 的 Cookie 文件恢复到上一个备份版本（
            <code>{restoreTarget.fileName}.bak</code>）吗？
          </p>
          <p style={{ margin: 0, fontSize: "12px", color: "var(--text-muted)" }}>
            恢复后，当前的 Cookie 文件将被替换，爬虫和转存服务将立即改用恢复后的 Cookie。
          </p>
        </Modal>
      )}

      {/* Delete Confirmation Modal */}
      {deleteTarget && (
        <Modal
          open={Boolean(deleteTarget)}
          title="确认删除 Cookie"
          onClose={deleting ? () => undefined : () => setDeleteTarget(null)}
          footer={
            <>
              <button
                type="button"
                className="admin-btn"
                onClick={() => setDeleteTarget(null)}
                disabled={deleting}
              >
                取消
              </button>
              <button
                type="button"
                className="admin-btn is-danger"
                onClick={() => void handleConfirmDelete()}
                disabled={deleting}
              >
                {deleting ? "正在删除..." : "确认删除"}
              </button>
            </>
          }
        >
          <p style={{ margin: "16px 0", fontSize: "14px", lineHeight: "1.6" }}>
            确定要删除 <strong>{deleteTarget.displayName}</strong> 的 Cookie 文件（
            <code>{deleteTarget.fileName}</code>）吗？
          </p>
          <p style={{ margin: 0, fontSize: "12px", color: "var(--text-muted)" }}>
            删除后，系统会自动保留一份 <code>.bak</code> 备份文件，方便随时一键恢复。
          </p>
        </Modal>
      )}
    </div>
  );
}
